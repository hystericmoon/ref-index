// Prints SQL that stores the written design notes in showcase_designs (design_md, generated_at)
// and sets the home-page pattern tags (showcase_pages position 0). Input: JSON files holding
// [{ id, design_md, home_patterns }].
//
// Run:  node scripts/designs-sql.ts tmp/designs/out > tmp/designs.sql
//       .\node_modules\.bin\supabase db query --linked -f tmp/designs.sql

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

type Entry = { id: string; design_md: string; home_patterns?: string[] };
const PATTERNS = new Set("hero-video big-type grid horizontal-scroll sticky-nav split-screen marquee full-bleed-image carousel editorial-layout dark-mode illustration 3d-webgl minimal".split(" "));
const dir = process.argv[2];
if (!dir) throw new Error("Pass the folder with the batch JSON files");
const entries = readdirSync(dir).filter((f) => /^b\d+\.json$/.test(f)).sort().flatMap((f) => JSON.parse(readFileSync(join(dir, f), "utf8")) as Entry[]);
const uuid = (id: string) => `'${id.replace(/[^0-9a-f-]/g, "")}'::uuid`;
const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines = ["-- Generated by scripts/designs-sql.ts"];
for (let i = 0; i < entries.length; i += 25) {
  const chunk = entries.slice(i, i + 25);
  const notes = chunk.map((e) => `(${uuid(e.id)}, ${quote(e.design_md.trim() + "\n")})`);
  lines.push(
    `insert into public.showcase_designs (item_id, design_md, generated_at) select v.id, v.d, now() from (values ${notes.join(",\n")}) v(id, d) on conflict (item_id) do update set design_md = excluded.design_md, generated_at = excluded.generated_at;`,
  );
}
const pats = entries.map((e) => `(${uuid(e.id)}, '{${(e.home_patterns ?? []).filter((p) => PATTERNS.has(p)).join(",")}}'::text[])`);
for (let i = 0; i < pats.length; i += 100) {
  lines.push(`update public.showcase_pages p set patterns = v.ps from (values ${pats.slice(i, i + 100).join(",\n")}) v(id, ps) where p.item_id = v.id and p.position = 0;`);
}
process.stdout.write(lines.join("\n") + "\n");
