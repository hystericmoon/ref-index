// Homepage thumbnails for the directory. Visits each source's home_url at 1440×900 in
// Chromium, saves a WebP to public/sources/<slug>.webp, and prints SQL that sets
// sources.thumb_path. Only homepages: gallery content is never crawled or saved.
//
// Run:  node scripts/capture-sources.ts > tmp/source-thumbs.sql
//       .\node_modules\.bin\supabase db query --linked -f tmp/source-thumbs.sql
// Needs NEXT_PUBLIC_SUPABASE_URL and NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY in .env.local
// (sources are publicly readable) and `playwright install chromium` once.

import { mkdirSync, readFileSync } from "node:fs";
import { chromium } from "playwright";
import sharp from "sharp";

type Source = { name: string; home_url: string };

function env(name: string): string {
  const line = readFileSync(".env.local", "utf8")
    .split(/\r?\n/)
    .find((l) => l.startsWith(`${name}=`));
  const value = line?.slice(name.length + 1).trim();
  if (!value) throw new Error(`${name} is missing from .env.local`);
  return value;
}

const slug = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const lit = (value: string) => `'${value.replace(/'/g, "''")}'`;

const url = env("NEXT_PUBLIC_SUPABASE_URL");
const key = env("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY");
const response = await fetch(`${url}/rest/v1/sources?select=name,home_url&active=eq.true&order=sort_order`, {
  headers: { apikey: key },
});
if (!response.ok) throw new Error(`Couldn't read sources: ${response.status}`);
const sources = (await response.json()) as Source[];

mkdirSync("public/sources", { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({
  viewport: { width: 1440, height: 900 },
  deviceScaleFactor: 1,
  reducedMotion: "reduce",
});
const updates: string[] = [];

for (const source of sources) {
  const page = await context.newPage();
  const file = `${slug(source.name)}.webp`;
  try {
    await page.goto(source.home_url, { waitUntil: "load", timeout: 45_000 });
    await page.waitForTimeout(2500);
    // Bot checks and blank pages make useless thumbnails; skip them rather than work around them.
    const text = (await page.locator("body").innerText({ timeout: 5_000 }).catch(() => "")).slice(0, 2000);
    if (/security verification|just a moment|verify you are human|checking your browser/i.test(text)) {
      throw new Error("bot check page");
    }
    if (text.trim().length < 20) throw new Error("page looks blank");
    const png = await page.screenshot({ type: "png" });
    await sharp(png).resize({ width: 960 }).webp({ quality: 72 }).toFile(`public/sources/${file}`);
    updates.push(`update public.sources set thumb_path = ${lit(`/sources/${file}`)} where name = ${lit(source.name)};`);
    console.error(`ok    ${source.name}`);
  } catch (error) {
    console.error(`fail  ${source.name}: ${(error as Error).message.split("\n")[0]}`);
  } finally {
    await page.close();
  }
}

await browser.close();
process.stdout.write(`-- Generated by scripts/capture-sources.ts\n${updates.join("\n")}\n`);
