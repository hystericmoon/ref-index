// Finds the live address of showcase items that only link to a gallery page. Reads each
// item's gallery page once and takes the gallery's own "visit website" link; nothing else
// on the page (images, text) is kept. One request per 1.5 s per gallery, robots.txt allowed.
// Links to archive.org copies are ignored: the site itself is gone.
//
// Run:  supabase db query --linked -f scripts/sql/linkless-items.sql -o json > tmp/resolve/input.json
//       node scripts/resolve-showcase-urls.ts tmp/resolve/input.json tmp/resolve/found.ndjson
//       node scripts/resolve-showcase-urls.ts --sql tmp/resolve/found.ndjson > tmp/resolve/set-urls.sql
// Resumable: items already in the output file are skipped.

import { appendFileSync, existsSync, readFileSync } from "node:fs";

type Row = { id: string; name: string; gallery: string; source_url: string };
type Found = { id: string; url: string | null };

// The visit link on each gallery's item page.
const PATTERNS: Record<string, RegExp[]> = {
  "One Page Love": [/<a href="([^"]+)"[^>]*title="Visit [^"]* Website"/i],
  Httpster: [/<a class="WebsiteView__ext" href="([^"]+)"/i],
  "Minimal Gallery": [/<a class="single-post-gallery-button" href="([^"]+)"/i],
};
const GENERIC = [
  /<a[^>]+href="(https?:\/\/[^"]+)"[^>]*(?:title|aria-label)="(?:Visit|Launch) (?:the )?(?:[^"]* )?(?:site|website)"/i,
  />\s*(?:Visit|Launch) (?:site|website)\s*</i,
];
const GAP_MS = 1500;
const UA = "Mozilla/5.0 (compatible; RefIndexBot/1.0; +https://ref-index.vercel.app)";

function clean(raw: string): string | null {
  try {
    const url = new URL(raw.replace(/&amp;/g, "&"));
    if (!/^https?:$/.test(url.protocol) || /(^|\.)web\.archive\.org$/.test(url.hostname)) return null;
    for (const key of [...url.searchParams.keys()]) {
      if (/^(ref|via|utm_.*|source)$/i.test(key)) url.searchParams.delete(key);
    }
    return url.toString();
  } catch {
    return null;
  }
}

function extract(html: string, gallery: string): string | null {
  for (const pattern of PATTERNS[gallery] ?? []) {
    const match = html.match(pattern);
    if (match) return clean(match[1]);
  }
  for (const pattern of GENERIC) {
    const match = html.match(pattern);
    if (match?.[1]) return clean(match[1]);
    if (match) {
      // Text-only match: take the href of the anchor that holds it.
      const before = html.slice(0, match.index);
      const href = before.slice(before.lastIndexOf("<a ")).match(/href="(https?:\/\/[^"]+)"/);
      if (href) return clean(href[1]);
    }
  }
  return null;
}

function sql(file: string) {
  const found = readFileSync(file, "utf8")
    .split("\n")
    .filter(Boolean)
    .map((l) => JSON.parse(l) as Found)
    .filter((f): f is { id: string; url: string } => !!f.url);
  const lit = (v: string) => `'${v.replace(/'/g, "''")}'`;
  const values = found.map((f) => `(${lit(f.id.replace(/[^0-9a-f-]/g, ""))}::uuid, ${lit(f.url)})`);
  // An item whose found address matches another item of the same name is merged into it.
  process.stdout.write(`-- Generated by scripts/resolve-showcase-urls.ts
create temp table found (id uuid, url text) on commit drop;
insert into found values
${values.join(",\n")};
insert into public.showcase_features (item_id, gallery, source_url, first_seen)
select o.id, f.gallery, f.source_url, f.first_seen
from found x
join public.showcase_items i on i.id = x.id
join public.showcase_items o on o.id <> i.id and o.name = i.name and o.url = x.url
join public.showcase_features f on f.item_id = i.id
on conflict do nothing;
delete from public.showcase_items i using found x, public.showcase_items o
where i.id = x.id and o.id <> i.id and o.name = i.name and o.url = x.url;
update public.showcase_items i set url = x.url from found x where i.id = x.id and i.url is null;
`);
}

async function resolve(inputFile: string, outFile: string) {
  const rows = (JSON.parse(readFileSync(inputFile, "utf8")).rows ?? JSON.parse(readFileSync(inputFile, "utf8"))) as Row[];
  const done = new Set(
    existsSync(outFile)
      ? readFileSync(outFile, "utf8")
          .split("\n")
          .filter(Boolean)
          .map((l) => (JSON.parse(l) as Found).id)
      : [],
  );
  const byHost = new Map<string, Row[]>();
  for (const row of rows) {
    if (done.has(row.id)) continue;
    const host = new URL(row.source_url).hostname;
    byHost.set(host, [...(byHost.get(host) ?? []), row]);
  }
  console.error([...byHost].map(([h, r]) => `${h}: ${r.length}`).join(", "));

  let count = 0;
  let hits = 0;
  await Promise.all(
    [...byHost.values()].map(async (list) => {
      for (const row of list) {
        const started = Date.now();
        let url: string | null = null;
        try {
          const response = await fetch(row.source_url, { headers: { "user-agent": UA }, redirect: "follow" });
          if (response.status === 429 || response.status === 403) {
            console.error(`stopping ${row.gallery}: ${response.status}`);
            return;
          }
          if (response.ok) url = extract(await response.text(), row.gallery);
        } catch {
          // Network error: recorded as not found.
        }
        appendFileSync(outFile, JSON.stringify({ id: row.id, url }) + "\n");
        if (url) hits++;
        if (++count % 100 === 0) console.error(`${count} read, ${hits} addresses found`);
        await new Promise((r) => setTimeout(r, Math.max(0, GAP_MS - (Date.now() - started))));
      }
    }),
  );
  console.error(`done: ${count} read, ${hits} addresses found`);
}

if (process.argv[2] === "--sql") sql(process.argv[3]);
else await resolve(process.argv[2], process.argv[3]);
