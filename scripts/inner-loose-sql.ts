// Prints SQL that records a top-up batch from scripts/capture-inner-loose.ts: appends the new
// pages to showcase_items.details.pages and adds showcase_pages rows (untagged, so they show up
// for page-type tagging) after the site's last position.
//
// Run:  node scripts/inner-loose-sql.ts tmp/showcase-details-v5/batch-1 > tmp/loose-1.sql
//       .\node_modules\.bin\supabase db query --linked -f tmp/loose-1.sql

import { readFileSync } from "node:fs";
import { join } from "node:path";

type Result = { id: string; ok: boolean; newPages?: { path: string; url: string; title: string }[] };
const dir = process.argv[2];
if (!dir) throw new Error("Pass the batch folder");
const results = readFileSync(join(dir, "results.ndjson"), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l) as Result).filter((r) => r.ok && r.newPages?.length);
const uuid = (id: string) => `'${id.replace(/[^0-9a-f-]/g, "")}'::uuid`;
const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines = ["-- Generated by scripts/inner-loose-sql.ts"];
if (results.length) {
  const values = results.map((r) => `(${uuid(r.id)}, ${quote(JSON.stringify(r.newPages))}::jsonb)`).join(",\n");
  lines.push(
    `with v(id, pages) as (values ${values}),`,
    `upd as (update public.showcase_items s set details = jsonb_set(s.details, '{pages}', coalesce(s.details->'pages', '[]'::jsonb) || v.pages) from v where s.id = v.id returning s.id)`,
    `insert into public.showcase_pages (item_id, position, path, url, title)`,
    `select v.id, coalesce((select max(position) from public.showcase_pages sp where sp.item_id = v.id), 0) + p.ord::int, p.page->>'path', p.page->>'url', p.page->>'title'`,
    `from v, jsonb_array_elements(v.pages) with ordinality as p(page, ord) on conflict do nothing;`,
  );
}
process.stdout.write(lines.join("\n") + "\n");
