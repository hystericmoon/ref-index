// Turns showcase entries into idempotent SQL: new items and new gallery credits are
// inserted, existing ones are left alone, nothing is deleted.
// Used by the seed (node scripts/showcase-sql.mjs docs/showcase.json > supabase/migrations/…_seed_showcase.sql)
// and by scripts/refresh-showcase.ts.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const lit = (value) => (value == null ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const arr = (values) => `array[${values.map(lit).join(", ")}]::text[]`;

/**
 * @param {{name: string, url: string|null, platform: string, tags: string[], featured: {g: string, src: string}[]}[]} entries
 * @param {string} firstSeen ISO date
 */
export function showcaseSql(entries, firstSeen) {
  if (!entries.length) return "-- nothing to add\n";
  const items = entries
    .map((e) => `  (${lit(e.name)}, ${lit(e.url)}, ${lit(e.platform)}, ${arr(e.tags ?? [])}, ${lit(firstSeen)}::date)`)
    .join(",\n");
  const features = entries
    .flatMap((e) => e.featured.map((f) => `  (${lit(e.name)}, ${lit(e.url)}, ${lit(f.g)}, ${lit(f.src)}, ${lit(firstSeen)}::date)`))
    .join(",\n");
  return `insert into public.showcase_items (name, url, platform, tags, first_seen) values
${items}
on conflict (name, url) do nothing;

insert into public.showcase_features (item_id, gallery, source_url, first_seen)
select i.id, f.gallery, f.source_url, f.first_seen
from (values
${features}
) as f (name, url, gallery, source_url, first_seen)
join public.showcase_items i on i.name = f.name and i.url is not distinct from f.url
on conflict (item_id, gallery) do nothing;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [file, firstSeen = "2026-10-27"] = process.argv.slice(2);
  const entries = JSON.parse(readFileSync(file, "utf8"));
  process.stdout.write(`-- Generated by scripts/showcase-sql.mjs from ${file}. Do not edit by hand.\n\n${showcaseSql(entries, firstSeen)}`);
}
