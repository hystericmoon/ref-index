// Local run of the daily showcase refresh: reads each gallery's newest picks (same code
// as the showcase-refresh Edge Function) and prints SQL that adds them. Nothing is deleted.
//
// Run:  node scripts/refresh-showcase.ts > tmp/showcase-refresh.sql
//       .\node_modules\.bin\supabase db query --linked -f tmp/showcase-refresh.sql
// The Edge Function does the same every Monday, so this is only needed for a one-off.

import { readAllGalleries } from "../supabase/functions/showcase-refresh/galleries.ts";

const { found, report } = await readAllGalleries();
for (const [gallery, line] of Object.entries(report)) console.error(`${gallery}: ${line}`);

// Entries named only from their own page (sitemap galleries) need the Edge Function's resolveLive.
const json = JSON.stringify(found.filter((f) => f.name)).replace(/'/g, "''");
process.stdout.write(
  `-- Generated by scripts/refresh-showcase.ts on ${new Date().toISOString().slice(0, 10)}\n` +
    `select public.add_showcase_entries('${json}'::jsonb);\n`,
);
