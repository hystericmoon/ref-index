// Prints SQL that stores the measured facts from scripts/extract-facts.ts in showcase_designs
// (facts, facts_at); design_md is left as it is.
//
// Run:  node scripts/facts-sql.ts tmp/designs > tmp/facts.sql
//       .\node_modules\.bin\supabase db query --linked -f tmp/facts.sql

import { readFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("Pass the output folder");
const rows = readFileSync(join(dir, "facts.ndjson"), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l) as { id: string });
const uuid = (id: string) => `'${id.replace(/[^0-9a-f-]/g, "")}'::uuid`;
const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const values = rows.map((r) => {
  const { id, ...facts } = r;
  return `(${uuid(id)}, ${quote(JSON.stringify(facts))}::jsonb)`;
});
const lines = ["-- Generated by scripts/facts-sql.ts"];
for (let i = 0; i < values.length; i += 100) {
  lines.push(
    `insert into public.showcase_designs (item_id, facts, facts_at) select v.id, v.f, now() from (values ${values.slice(i, i + 100).join(",\n")}) v(id, f) on conflict (item_id) do update set facts = excluded.facts, facts_at = excluded.facts_at;`,
  );
}
process.stdout.write(lines.join("\n") + "\n");
