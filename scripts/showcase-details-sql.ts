// Prints SQL that records a detail-capture batch from scripts/capture-details.ts: sets details
// for captured items, details_checked_at for every item tried, and flags parked or taken-over
// domains for /curate's "Flagged by AI" queue (nothing is hidden).
//
// Run:  node scripts/showcase-details-sql.ts tmp/showcase-details/batch-1 > tmp/details-1.sql
//       .\node_modules\.bin\supabase db query --linked -f tmp/details-1.sql

import { readFileSync } from "node:fs";
import { join } from "node:path";

type Result = { id: string; ok: boolean; reason?: string | null; full?: string; fullHeight?: number; pages?: unknown[] };

const dir = process.argv[2];
if (!dir) throw new Error("Pass the batch folder");

const results = readFileSync(join(dir, "results.ndjson"), "utf8")
  .split("\n")
  .filter(Boolean)
  .map((line) => JSON.parse(line) as Result)
  // Blocked by the capturing machine's network: not a verdict on the site, so left unchecked.
  .filter((r) => r.reason !== "blocked on this network");

const uuid = (id: string) => `'${id.replace(/[^0-9a-f-]/g, "")}'::uuid`;
const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines = ["-- Generated by scripts/showcase-details-sql.ts"];

const captured = results.filter((r) => r.ok && r.full);
if (captured.length) {
  const values = captured.map((r) => `(${uuid(r.id)}, ${quote(JSON.stringify({ full: r.full, fullHeight: r.fullHeight, pages: r.pages ?? [] }))}::jsonb)`);
  lines.push(
    `update public.showcase_items s set details = v.d, details_checked_at = now() from (values ${values.join(",\n")}) v(id, d) where s.id = v.id;`,
  );
}
const failed = results.filter((r) => !r.ok).map((r) => uuid(r.id));
if (failed.length) {
  lines.push(`update public.showcase_items set details_checked_at = now() where id in (${failed.join(",")});`);
}
const replaced = results.filter((r) => r.reason === "parked or replaced domain").map((r) => uuid(r.id));
if (replaced.length) {
  lines.push(
    `update public.showcase_items set ai_flag = 'broken', ai_checked_at = now() where ai_flag is null and staff_pick is not true and id in (${replaced.join(",")});`,
  );
}
process.stdout.write(lines.join("\n") + "\n");
