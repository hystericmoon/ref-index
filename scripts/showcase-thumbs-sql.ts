// Prints SQL that records a capture batch from scripts/capture-showcase.ts: sets
// thumb_path for captured items and thumb_checked_at for every item tried.
//
// Run:  node scripts/showcase-thumbs-sql.ts tmp/showcase-thumbs/batch-1 > tmp/thumbs-1.sql
//       .\node_modules\.bin\supabase db query --linked -f tmp/thumbs-1.sql

import { readFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("Pass the batch folder");

const results = readFileSync(join(dir, "results.ndjson"), "utf8")
  .split("\n")
  .filter(Boolean)
  .map((line) => JSON.parse(line) as { id: string; ok: boolean; reason?: string | null })
  // Blocked by the capturing machine's network: not a verdict on the site, so left unchecked.
  .filter((r) => r.reason !== "blocked on this network");
const ids = (ok: boolean) => results.filter((r) => r.ok === ok).map((r) => `'${r.id.replace(/[^0-9a-f-]/g, "")}'`);

const captured = ids(true);
const failed = ids(false);
const lines = ["-- Generated by scripts/showcase-thumbs-sql.ts"];
if (captured.length) {
  lines.push(
    `update public.showcase_items set thumb_path = 'img/' || id::text || '.webp', thumb_checked_at = now() where id in (${captured.join(",")});`,
  );
}
if (failed.length) {
  lines.push(`update public.showcase_items set thumb_checked_at = now() where id in (${failed.join(",")});`);
}
process.stdout.write(lines.join("\n") + "\n");
